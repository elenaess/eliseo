export function findInstitutionForEmail(
  email: string,
): InstitutionalDomain | null {
  const clean =
    email
      .trim()
      .toLowerCase();

  const at =
    clean.lastIndexOf('@');

  if (
    at <= 0 ||
    at === clean.length - 1
  ) {
    return null;
  }

  const domain =
    clean.slice(at + 1);

  return (
    institutionalDomains.find(
      item =>
        item.domain ===
        domain,
    ) ??
    null
  );
}
